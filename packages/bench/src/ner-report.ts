import { writeFileSync } from "node:fs";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createNerDetector, DEFAULT_MODEL_ID } from "@maskit/ner";
import { runRealistic, runRealisticWith } from "./evaluate.js";
import { listItems, renderRealisticSummary, renderRealisticTable } from "./report.js";

export const MODEL_ROOT = fileURLToPath(new URL("../../ner/models/", import.meta.url));
export const modelAvailable = () =>
  existsSync(`${MODEL_ROOT}${DEFAULT_MODEL_ID}/onnx/model_quantized.onnx`);

export async function renderNerMarkdown(): Promise<string> {
  const ner = await createNerDetector({ modelRoot: MODEL_ROOT });
  const out = [];
  for (const level of ["standard", "strict"] as const) {
    out.push({ rules: runRealistic(level), withNer: await runRealisticWith(level, [ner]) });
  }
  const summary = renderRealisticSummary(
    out.flatMap((o) => [
      { label: "rules only", report: o.rules },
      { label: "rules + name model", report: o.withNer },
    ]),
  );
  const standard = out[0]!.withNer;
  const strict = out[1]!.withNer;

  return `# Benchmarks with the on-device name model

> Generated by \`pnpm --filter @maskit/bench bench:ner\`. Needs the model files (\`pnpm --filter @maskit/ner fetch-model\`). Do not edit by hand.

The optional model finds names, organizations and places in free text, where the rules need a label such as "Patient:" or "Dr.". Model: \`${DEFAULT_MODEL_ID}\` (DistilBERT fine-tuned for English named-entity recognition, 8-bit quantized, about 66 MB), run locally; hits pass through the same level, confidence and overlap rules as the rules do, after generic filters (greeting words, sentence-opening verbs, short all-caps abbreviations, lowercase words, dotted initials).

**Same caveats as BENCHMARKS.md:** the same 32 hand-written documents, labeled by the author, English only. The filters were chosen after looking at this model's mistakes on this set, so the numbers are somewhat optimistic for unseen text.

## Overall
${summary}

## Per type at the strict level (rules + name model)
${renderRealisticTable(strict)}

## What is still missed or wrongly flagged
- Default (standard) level, missed: ${listItems(standard.misses)}
- Default (standard) level, false alarms: ${listItems(standard.falseAlarms)}
- Strict level, missed: ${listItems(strict.misses)}
- Strict level, false alarms: ${listItems(strict.falseAlarms)}

## Limits
- English only. The model was trained on news text, so unusual or non-Western names, lowercase text and short chat messages are weaker.
- Organizations and places depend on the model; a company named like a common word may be missed.
- Adds a 66 MB download and about 20 ms per sentence on a laptop CPU.
`;
}

if (process.argv[1] && /ner-report\.ts$/.test(process.argv[1].replace(/\\/g, "/"))) {
  if (!modelAvailable()) {
    console.error("Model not found. Run: pnpm --filter @maskit/ner fetch-model");
    process.exit(1);
  }
  const md = await renderNerMarkdown();
  writeFileSync(new URL("../../../docs/BENCHMARKS-NER.md", import.meta.url), md);
  console.log(md);
}

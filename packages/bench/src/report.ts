import { writeFileSync } from "node:fs";
import { NEGATIVE_COUNT, PER_TYPE, ratio, runBenchmark, SEED, type Report } from "./evaluate.js";

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

export function renderMarkdown(r: Report): string {
  const rows = r.perType
    .map((s) => {
      const p = ratio(s.tp, s.tp + s.fp);
      const rec = ratio(s.tp, s.tp + s.fn);
      const f1 = ratio(2 * p * rec, p + rec);
      return `| ${s.type} | ${s.total} | ${pct(p)} | ${pct(rec)} | ${pct(f1)} | ${pct(ratio(s.covered, s.total))} |`;
    })
    .join("\n");
  const hard = r.hard
    .map(
      (h) =>
        `| ${h.name} | ${h.total} | ${pct(ratio(h.typedHits, h.total))} | ${pct(ratio(h.covered, h.total))} | ${pct(ratio(h.coveredStandard, h.total))} |`,
    )
    .join("\n");
  const negs = r.negatives
    .map((n) => `| ${n.level} | ${n.lines} | ${n.flagged} | ${pct(ratio(n.flagged, n.lines))} |`)
    .join("\n");
  const examples = r.negatives
    .filter((n) => n.examples.length > 0)
    .map((n) => `- ${n.level}: ${n.examples.map((e) => "`" + e + "`").join("; ")}`)
    .join("\n");

  return `# Benchmarks

> Generated by \`pnpm --filter @maskit/bench bench\`. Do not edit by hand; rerun the command and commit the result.

## Read this first
These numbers come from a **synthetic** dataset that I wrote, using the same kinds of formats the recognizers were designed around. They show that the rules work as intended and let CI catch regressions. They are **not** a measure of accuracy on real documents, which are messier, and they are likely optimistic. Real-world accuracy has not been measured. The recognizers were also adjusted after the first run of this benchmark exposed bugs (see CHANGELOG), so the same data that found the problems now shows a perfect score: treat 100% here as "no known regressions", never as "100% accurate". The "known gaps" table below shows the cases the rules layer is expected to miss.

## Method
- Dataset: seed ${SEED}, ${PER_TYPE} generated sentences per entity type, each embedding one labeled value with random surrounding text. Card, IBAN and routing numbers carry valid checksums. Secrets are assembled from parts so secret scanners do not flag the repository.
- Positive cases are scored at the **strict** level (all types on). A prediction is a true positive when its type matches and its span overlaps the labeled value with IoU of at least 0.5. Extra findings of another type count as false positives.
- "Masked at all" is the privacy-relevant figure: the labeled value was at least half covered by *some* finding, even if the label differs.
- Negatives: ${NEGATIVE_COUNT} lines of ordinary text (code, versions, invoice and order numbers, times, hashes, UUIDs, SQL, prose) that should not be masked.

## Overall (strict level)
| Precision | Recall | F1 | Masked at all |
|---|---|---|---|
| ${pct(r.overall.precision)} | ${pct(r.overall.recall)} | ${pct(r.overall.f1)} | ${pct(r.overall.covered)} |

## Per entity type
| Type | Cases | Precision | Recall | F1 | Masked at all |
|---|---|---|---|---|---|
${rows}

## False positives on ordinary text
| Level | Lines | Lines wrongly flagged | Rate |
|---|---|---|---|
${negs}

${examples ? `Examples of lines flagged:\n${examples}\n` : "No ordinary line was flagged at any level.\n"}
## Known gaps (cases the rules layer is expected to miss)
100 cases each. "Right label" means the type matched; "Masked at all" means something covered the value. Shown for strict (most sensitive) and standard (default).

| Case | Cases | Right label (strict) | Masked at all (strict) | Masked at all (standard) |
|---|---|---|---|---|
${hard}

These gaps are why the review step exists and why NER (free-text names and organizations) is planned. They are also why no tool should be trusted to catch everything.
`;
}

if (process.argv[1] && /report\.ts$/.test(process.argv[1].replace(/\\/g, "/"))) {
  const md = renderMarkdown(runBenchmark());
  const out = new URL("../../../docs/BENCHMARKS.md", import.meta.url);
  writeFileSync(out, md);
  console.log(md);
}

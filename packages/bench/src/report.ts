import { writeFileSync } from "node:fs";
import {
  NEGATIVE_COUNT,
  PER_TYPE,
  ratio,
  runBenchmark,
  runRealistic,
  SEED,
  type RealisticReport,
  type Report,
} from "./evaluate.js";

export const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

const NL = "\n";

export function renderRealisticTable(r: RealisticReport): string {
  const rows = r.perType
    .map((s) => {
      const p = ratio(s.tp, s.tp + s.fp);
      const rec = ratio(s.tp, s.tp + s.fn);
      return `| ${s.type} | ${s.total} | ${s.tp} | ${s.fn} | ${s.fp} | ${pct(p)} | ${pct(rec)} |`;
    })
    .join(NL);
  return [
    "| Type | Labeled | Found | Missed | False alarms | Precision | Recall |",
    "|---|---|---|---|---|---|---|",
    rows,
  ].join(NL);
}

export function renderRealisticSummary(
  reports: { label: string; report: RealisticReport }[],
): string {
  const rows = reports
    .map(
      ({ label, report: r }) =>
        `| ${label} | ${r.level} | ${r.gold} | ${pct(r.overall.precision)} | ${pct(r.overall.recall)} | ${pct(r.overall.f1)} | ${pct(r.overall.covered)} |`,
    )
    .join(NL);
  return [
    "| Detection | Level | Labeled values | Precision | Recall | F1 | Masked at all |",
    "|---|---|---|---|---|---|---|",
    rows,
  ].join(NL);
}

export const listItems = (items: { type: string; value: string }[]): string =>
  items.length === 0 ? "none" : items.map((i) => "`" + i.type + ": " + i.value + "`").join(", ");

export function renderMarkdown(r: Report): string {
  const rows = r.perType
    .map((s) => {
      const p = ratio(s.tp, s.tp + s.fp);
      const rec = ratio(s.tp, s.tp + s.fn);
      const f1 = ratio(2 * p * rec, p + rec);
      return `| ${s.type} | ${s.total} | ${pct(p)} | ${pct(rec)} | ${pct(f1)} | ${pct(ratio(s.covered, s.total))} |`;
    })
    .join(NL);
  const hard = r.hard
    .map(
      (h) =>
        `| ${h.name} | ${h.total} | ${pct(ratio(h.typedHits, h.total))} | ${pct(ratio(h.covered, h.total))} | ${pct(ratio(h.coveredStandard, h.total))} |`,
    )
    .join(NL);
  const negs = r.negatives
    .map((n) => `| ${n.level} | ${n.lines} | ${n.flagged} | ${pct(ratio(n.flagged, n.lines))} |`)
    .join(NL);
  const examples = r.negatives
    .filter((n) => n.examples.length > 0)
    .map((n) => `- ${n.level}: ${n.examples.map((e) => "`" + e + "`").join("; ")}`)
    .join(NL);

  const standard = runRealistic("standard");
  const strict = runRealistic("strict");

  return `# Benchmarks

> Generated by \`pnpm --filter @maskit/bench bench\`. Do not edit by hand; rerun the command and commit the result.

## Read this first
Two test sets are used, and **neither is real-world data**. The generated set (first sections) was produced by code I wrote around the same formats the recognizers were designed for, and the recognizers were adjusted after its first run exposed bugs (see CHANGELOG), so its perfect score means "no known regressions", never "100% accurate". The hand-written realistic set (further down) is messier and gives a more honest, lower number, but it is small and labeled by the author. Real-world accuracy has not been measured.

## Method (generated set)
- Dataset: seed ${SEED}, ${PER_TYPE} generated sentences per entity type, each embedding one labeled value with random surrounding text. Card, IBAN and routing numbers carry valid checksums. Secrets are assembled from parts so secret scanners do not flag the repository.
- Positive cases are scored at the **strict** level (all types on). A prediction is a true positive when its type matches and its span overlaps the labeled value with IoU of at least 0.5. Extra findings of another type count as false positives.
- "Masked at all" is the privacy-relevant figure: the labeled value was at least half covered by *some* finding, even if the label differs.
- Negatives: ${NEGATIVE_COUNT} lines of ordinary text (code, versions, invoice and order numbers, times, hashes, UUIDs, SQL, prose) that should not be masked.

## Overall (generated set, strict level)
| Precision | Recall | F1 | Masked at all |
|---|---|---|---|
| ${pct(r.overall.precision)} | ${pct(r.overall.recall)} | ${pct(r.overall.f1)} | ${pct(r.overall.covered)} |

## Per entity type (generated set)
| Type | Cases | Precision | Recall | F1 | Masked at all |
|---|---|---|---|---|---|
${rows}

## False positives on ordinary text
| Level | Lines | Lines wrongly flagged | Rate |
|---|---|---|---|
${negs}

${examples ? `Examples of lines flagged:\n${examples}\n` : "No ordinary line was flagged at any level.\n"}
## Hand-written realistic set (rules only)
${renderRealisticSummary([
  { label: "rules only", report: standard },
  { label: "rules only", report: strict },
])}

${standard.docs} short documents written by hand in a different style from the generated cases: a clinical note, business emails, a support chat, server logs, an HR record, a contract, a lab report, shared credentials, an env file, an insurance record, JSON, an email header, and so on, plus a few with nothing sensitive in them. All names and numbers are invented. Only values the level is meant to mask are counted (plain dates, ages over 89, organizations and locations count at strict only).

Per type at the strict level:

${renderRealisticTable(strict)}

Missed at the default (standard) level: ${listItems(standard.misses)}

False alarms at the default (standard) level: ${listItems(standard.falseAlarms)}

Names that appear without a label ("Hi Priya", "Regards, Tom Becker", "Her daughter Elena Gonzalez") are the main misses of the rules layer, and organizations and places have no rules at all. The optional on-device name model closes most of that gap: see [BENCHMARKS-NER.md](BENCHMARKS-NER.md).

## Known gaps (generated cases the rules layer is expected to miss)
100 cases each. "Right label" means the type matched; "Masked at all" means something covered the value. Shown for strict (most sensitive) and standard (default).

| Case | Cases | Right label (strict) | Masked at all (strict) | Masked at all (standard) |
|---|---|---|---|---|
${hard}

These gaps are why the review step exists. They are also why no tool should be trusted to catch everything.
`;
}

if (process.argv[1] && /report\.ts$/.test(process.argv[1].replace(/\\/g, "/"))) {
  const md = renderMarkdown(runBenchmark());
  const out = new URL("../../../docs/BENCHMARKS.md", import.meta.url);
  writeFileSync(out, md);
  console.log(md);
}
